#!/usr/bin/env python3
"""Gzip web/ assets into src/net_core/web_assets.{h,cpp} (deterministic: mtime=0)."""
import gzip, io, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [("/index.html", "index.html", "text/html; charset=utf-8"), ("/app.js", "app.js", "text/javascript; charset=utf-8"),
         ("/setup.html", "setup.html", "text/html; charset=utf-8")]
out = ['// Generated by tools/embed_web.py from web/. Do not edit; edit web/ and re-run.',
       '#include "net_core/web_assets.h"', '', '#include <cstring>', '', 'namespace net {', '']
table = []
for i, (url, name, ctype) in enumerate(FILES):
    raw = open(os.path.join(ROOT, "web", name), "rb").read()
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0, filename="") as g:
        g.write(raw)
    data = buf.getvalue()
    out.append(f"// {name}: {len(raw)} bytes raw, {len(data)} gzipped")
    out.append(f"static const uint8_t kAsset{i}[] = {{")
    for j in range(0, len(data), 20):
        out.append("  " + ",".join(str(b) for b in data[j:j + 20]) + ",")
    out.append("};")
    table.append(f'  {{"{url}", "{ctype}", kAsset{i}, sizeof(kAsset{i}), {len(raw)}}},')
    print(f"{name}: {len(raw)} -> {len(data)} bytes")
out += ["", "static const WebAsset kAssets[] = {"] + table + ["};", "",
        "const WebAsset* findWebAsset(const std::string& path) {",
        "  for (const auto& a : kAssets)", "    if (path == a.path) return &a;", "  return nullptr;", "}", "",
        "size_t webAssetsTotalBytes() {", "  size_t n = 0;", "  for (const auto& a : kAssets) n += a.size;", "  return n;", "}", "",
        "}  // namespace net", ""]
open(os.path.join(ROOT, "src/net_core/web_assets.cpp"), "w").write("\n".join(out))
