#!/usr/bin/env python3
"""Generates the full-screen sleep/off logo frame (src/ui_core/assets/sleep_logo.cpp).

Input: raw 1-bit bitmap, 1080x758, MSB = leftmost pixel, bit 1 = white
(tools/rxnudge_logo_1080x758.bin). The last 3 columns are padding and are
dropped. The artwork is cropped, scaled to fit 800x480 with a margin and
centred. Output is one SSD1677 frame (100 B/row, bit 1 = white) kept in
flash, so it costs no RAM.
Usage: python3 tools/gen_sleep_logo.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "rxnudge_logo_1080x758.bin")
OUT = os.path.join(HERE, "..", "src", "ui_core", "assets", "sleep_logo.cpp")
W, H, MARGIN = 800, 480, 24

src = Image.frombytes("1", (1080, 758), open(SRC, "rb").read()).crop((0, 0, 1077, 758)).convert("L")
bbox = Image.eval(src, lambda v: 255 - v).getbbox()
art = src.crop(bbox)
s = min((W - 2 * MARGIN) / art.width, (H - 2 * MARGIN) / art.height)
art = art.resize((round(art.width * s), round(art.height * s)), Image.LANCZOS).point(lambda v: 255 if v >= 128 else 0)
frame = Image.new("L", (W, H), 255)
frame.paste(art, ((W - art.width) // 2, (H - art.height) // 2))
frame.convert("1").save(os.path.join(HERE, "..", "docs", "sleep_logo_preview.png"))
data = frame.convert("1").tobytes()
assert len(data) == W * H // 8
with open(OUT, "w") as f:
    f.write("// GENERATED by tools/gen_sleep_logo.py - do not edit.\n")
    f.write('#include "ui_core/assets/sleep_logo.h"\n\nnamespace ui {\n\n')
    f.write("const uint8_t kSleepLogoFrame[kSleepLogoBytes] = {\n")
    for i in range(0, len(data), 20):
        f.write("    " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",\n")
    f.write("};\n\n}  // namespace ui\n")
print("art %dx%d at scale %.3f" % (art.width, art.height, s))
