#!/usr/bin/env python3
"""Generates RxNudge UI assets (1-bit fonts and icons) as C++ sources.

Fonts: Atkinson Hyperlegible (SIL OFL 1.1), sizes in points at the
EpdFont convention of 150 dpi (size_px = pt * 150 / 72), Latin-1 + common
punctuation. Icons: drawn from primitives at 4x and downsampled to 40x40.
Usage: python3 tools/gen_assets.py <atkinson-font-dir>
"""
import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "ui_core", "assets")
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/sand-box/google/Atkinson Hyperlegible"

FONTS = [  # (symbol, file, points)
    ("atk14r", "AtkinsonHyperlegible-Regular.ttf", 14),
    ("atk18r", "AtkinsonHyperlegible-Regular.ttf", 18),
    ("atk18b", "AtkinsonHyperlegible-Bold.ttf", 18),
    ("atk24r", "AtkinsonHyperlegible-Regular.ttf", 24),
    ("atk24b", "AtkinsonHyperlegible-Bold.ttf", 24),
    ("atk40b", "AtkinsonHyperlegible-Bold.ttf", 40),
]
CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2212]

HEADER = "// GENERATED by tools/gen_assets.py - do not edit.\n"


def ranges(cps):
    out, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c != prev + 1:
            out.append((start, prev))
            start = c
        prev = c
    out.append((start, prev))
    return out


def gen_font(sym, path, pt):
    px = round(pt * 150 / 72)
    font = ImageFont.truetype(path, px)
    asc, desc = font.getmetrics()
    bits = []  # list of ints 0/1 appended per glyph, padded to byte per glyph
    data = bytearray()
    glyphs = []
    for cp in CODEPOINTS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        offset = len(data)
        if w > 0 and h > 0:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            acc, n = 0, 0
            for y in range(h):
                for x in range(w):
                    acc = (acc << 1) | (1 if img.getpixel((x, y)) >= 120 else 0)
                    n += 1
                    if n == 8:
                        data.append(acc)
                        acc, n = 0, 0
            if n:
                data.append(acc << (8 - n))
        else:
            w = h = 0
        assert 0 <= w < 256 and 0 <= h < 256 and adv < 256 and -128 <= l < 128 and -128 <= -t < 128, (sym, ch)
        glyphs.append((w, h, adv, l, -t, offset))
    rs = ranges(CODEPOINTS)
    idx, rlines = 0, []
    for a, z in rs:
        rlines.append(f"    {{0x{a:X}, 0x{z:X}, {idx}}},")
        idx += z - a + 1
    with open(os.path.join(OUT, f"font_{sym}.cpp"), "w") as f:
        f.write(HEADER)
        f.write('#include "ui_core/assets/fonts.h"\n\nnamespace ui {\nnamespace {\n')
        f.write(f"const uint8_t kBits[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 24]) + ",\n")
        f.write("};\nconst Glyph kGlyphs[] = {\n")
        for (w, h, adv, l, top, off), cp in zip(glyphs, CODEPOINTS):
            f.write(f"    {{{w}, {h}, {adv}, {l}, {top}, {off}}},  // U+{cp:04X}\n")
        f.write("};\nconst GlyphRange kRanges[] = {\n" + "\n".join(rlines) + "\n};\n}  // namespace\n\n")
        f.write(f"extern const Font {sym} = {{kBits, kGlyphs, kRanges, {len(rs)}, {asc}, {desc}, {asc + desc}, \"{sym}\"}};\n\n}}  // namespace ui\n")
    return len(data)


# ------------------------------------------------------------------ icons
S = 160  # supersampled canvas for a 40x40 icon
LW = 12


def capsule(d, box, fill_left=False):
    x0, y0, x1, y1 = box
    r = (y1 - y0) // 2
    d.rounded_rectangle(box, radius=r, outline=255, width=LW)
    if fill_left:
        mid = (x0 + x1) // 2
        d.rounded_rectangle((x0, y0, mid + r, y1), radius=r, fill=255)
        d.rectangle((mid, y0, mid + r, y1), fill=0)
        d.rounded_rectangle(box, radius=r, outline=255, width=LW)
        d.line((mid, y0, mid, y1), fill=255, width=LW)


def icon_pill(d):
    img = Image.new("L", (S, S), 0)
    dd = ImageDraw.Draw(img)
    capsule(dd, (14, 52, 146, 108), fill_left=False)
    dd.line((80, 52, 80, 108), fill=255, width=LW)
    return img.rotate(45, resample=Image.BICUBIC)


def icon_capsule(d):
    img = Image.new("L", (S, S), 0)
    capsule(ImageDraw.Draw(img), (10, 50, 150, 110), fill_left=True)
    return img.rotate(30, resample=Image.BICUBIC)


