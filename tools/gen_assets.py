def icon_charging(d):
    icon_battery(d, 0.0)
    d.polygon([(84, 50), (54, 84), (78, 84), (66, 112), (100, 76), (76, 76)], fill=255)


def gen_icons():
    size = 40
    rows = []
    for name, fn in ICONS:
        img = Image.new("L", (S, S), 0)
        d = ImageDraw.Draw(img)
        fn = fn or icon_charging
        r = fn(d)
        if isinstance(r, Image.Image):
            img = r
        small = img.resize((size, size), Image.LANCZOS)
        data = bytearray()
        for y in range(size):
            for xb in range(0, size, 8):
                v = 0
                for x in range(xb, xb + 8):
                    v = (v << 1) | (1 if small.getpixel((x, y)) >= 110 else 0)
                data.append(v)
        rows.append((name, data))
    with open(os.path.join(OUT, "icon_ids.h"), "w") as f:
        f.write(HEADER + "#pragma once\n#include <cstdint>\n\nnamespace ui {\n\nenum class IconId : uint8_t {\n")
        for name, _ in rows:
            f.write(f"  {name},\n")
        f.write("  Count,\n  None = 255\n};\n\nconstexpr int kIconSize = 40;\n\n}  // namespace ui\n")
    with open(os.path.join(OUT, "icons_data.cpp"), "w") as f:
        f.write(HEADER + '#include "ui_core/icons.h"\n\nnamespace ui {\n\nconst uint8_t kIconBits[][200] = {\n')
        for name, data in rows:
            f.write(f"    {{  // {name}\n")
            for i in range(0, len(data), 20):
                f.write("        " + ", ".join(f"0x{v:02X}" for v in data[i:i + 20]) + ",\n")
            f.write("    },\n")
        f.write("};\n\n}  // namespace ui\n")
    # preview sheet for docs
    sheet = Image.new("L", (len(rows) * 48, 48), 255)
    for i, (name, data) in enumerate(rows):
        for y in range(size):
            for x in range(size):
                if data[y * 5 + x // 8] & (0x80 >> (x % 8)):
                    sheet.putpixel((i * 48 + 4 + x, 4 + y), 0)
    os.makedirs(os.path.join(OUT, "..", "..", "..", "docs", "screens"), exist_ok=True)
    sheet.save(os.path.join(OUT, "..", "..", "..", "docs", "screens", "icons.png"))


def main():
    os.makedirs(OUT, exist_ok=True)
    total = 0
    with open(os.path.join(OUT, "fonts.h"), "w") as f:
        f.write(HEADER + '#pragma once\n#include "ui_core/text.h"\n\nnamespace ui {\n')
        for sym, _, pt in FONTS:
            f.write(f"extern const Font {sym};  // Atkinson Hyperlegible {pt} pt\n")
        f.write("}  // namespace ui\n")
    for sym, fn, pt in FONTS:
        n = gen_font(sym, os.path.join(FONT_DIR, fn), pt)
        total += n
        print(f"{sym}: {n} bytes")
    gen_icons()
    print(f"fonts total {total} bytes, {len(ICONS)} icons")


if __name__ == "__main__":
    main()
